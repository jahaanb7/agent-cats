    /// The text as an image: `fill` letters over a `shadow` one pixel down-right (an embossed arcade
    /// look). "@" draws the cat head, in `accent` when given.
    static func image(_ text: String, px: CGFloat, fill: NSColor, shadow: NSColor, accent: NSColor? = nil) -> NSImage {
        let rows = text.uppercased().map { glyphs[$0] ?? glyphs[" "]! }
        let cols = rows.reduce(0) { $0 + $1[0].count + 1 } - 1
        let size = NSSize(width: CGFloat(cols + 1) * px, height: 8 * px)
        let img = NSImage(size: size, flipped: true) { _ in
            for (pass, color) in [(1, shadow), (0, fill)] {
                var x = 0
                for (gi, g) in rows.enumerated() {
                    let isCat = Array(text.uppercased())[gi] == "@"
                    for (r, line) in g.enumerated() {
                        for (c, ch) in line.enumerated() where ch == "#" {
                            var col = color
                            if pass == 0, isCat, let accent { col = accent }
                            col.setFill()
                            NSRect(x: CGFloat(x + c + pass) * px, y: CGFloat(r + pass) * px, width: px, height: px).fill()
                        }
                    }
                    x += g[0].count + 1
                }
            }
            return true
        }
        return img
    }
